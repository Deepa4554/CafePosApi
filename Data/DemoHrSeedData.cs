/// <summary>
/// Optional, Development-only demo data for the Attendance / Payroll / Payslip screens.
///
/// Deliberately NOT part of <see cref="SeedData"/>: that file seeds catalog/config only
/// and documents that transactional data always starts empty. This is throwaway data for
/// looking at the HR UI with something in it, so it lives behind its own opt-in config
/// switch (<c>DemoData:SeedHrForTenantSlug</c>) and can be removed again in one flip
/// (<c>DemoData:PurgeHrDemo</c>).
///
/// Every row it writes is traceable back to here: staff carry <see cref="DemoEmailDomain"/>
/// e-mails and the payroll run carries <see cref="DemoRunNote"/>, which is exactly what
/// the purge path matches on — nothing typed in by a real user is ever touched.
/// </summary>
public static class DemoHrSeedData
{
