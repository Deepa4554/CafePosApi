    public static void Apply(CafePosDbContext db, ILogger logger, string? tenantSlug, string? ownerEmail, bool purge)
    {
        var tenant = ResolveTenant(db, logger, tenantSlug, ownerEmail);
        if (tenant is null) return;

        if (purge)
        {
            Purge(db, logger, tenant.Id);
            return;
        }

        // Global query filters resolve to the DEFAULT tenant at startup (there's no request
        // to read a JWT from), so every read here must ignore them and filter by hand.
        if (db.AttendanceRecords.IgnoreQueryFilters().Any(a => a.TenantId == tenant.Id))
        {
            logger.LogInformation("DemoData: tenant '{Slug}' already has attendance rows — skipping demo seed.", tenant.Slug);
            return;
        }

        var settings = db.Settings.IgnoreQueryFilters().FirstOrDefault(s => s.TenantId == tenant.Id) ?? new CafeSettings();
        var today = DateOnly.FromDateTime(DateTime.UtcNow);
        var periodStart = new DateOnly(today.Year, today.Month, 1).AddMonths(-1);
        var periodEnd = periodStart.AddMonths(1).AddDays(-1);

        var staff = SeedStaff(db, tenant.Id);
        LinkSignedInOwnerToRoster(db, logger, tenant.Id, ownerEmail, staff);
        var loans = SeedLoans(db, tenant.Id, staff);
        var leaves = SeedLeave(db, tenant.Id, staff);
        SeedShiftsAndAttendance(db, tenant.Id, staff, periodStart, today.AddDays(-1));
        db.SaveChanges();

        SeedPaidPayrollRun(db, tenant.Id, staff, loans, leaves, settings, periodStart, periodEnd);
        db.SaveChanges();

        logger.LogWarning(
            "DemoData: seeded {StaffCount} demo staff + attendance ({From} → {To}) and a PAID payroll run for {Period:yyyy-MM} into tenant '{Slug}'. "
            + "Set DemoData:PurgeHrDemo=true to remove it again.",
            staff.Count, periodStart, today.AddDays(-1), periodStart, tenant.Slug);
    }

    /// <summary>
    /// Either identifier works — the cafe's slug (shown on the Cafe Profile screen) or the
    /// e-mail you sign in with, because the slug isn't something anyone has memorised.
    /// Neither set means the whole feature stays off.
    /// </summary>
    private static Tenant? ResolveTenant(CafePosDbContext db, ILogger logger, string? tenantSlug, string? ownerEmail)
    {
        if (!string.IsNullOrWhiteSpace(ownerEmail))
        {
            // AppUser is deliberately not tenant-filtered (see its TenantId doc comment),
            // so an e-mail lookup works here at startup without IgnoreQueryFilters.
            var user = db.Users.FirstOrDefault(u => u.Email == ownerEmail);
            if (user is null)
            {
                logger.LogWarning("DemoData: no login found for '{Email}' — nothing seeded.", ownerEmail);
                return null;
            }
            var byUser = db.Tenants.FirstOrDefault(t => t.Id == user.TenantId);
            if (byUser is null) logger.LogWarning("DemoData: login '{Email}' points at tenant {TenantId}, which no longer exists.", ownerEmail, user.TenantId);
            return byUser;
        }

        if (string.IsNullOrWhiteSpace(tenantSlug)) return null;

        var tenant = db.Tenants.FirstOrDefault(t => t.Slug == tenantSlug);
        if (tenant is null)
        {
            logger.LogWarning(
                "DemoData: no tenant with slug '{Slug}' — nothing seeded. Known slugs: {Known}.",
                tenantSlug, string.Join(", ", db.Tenants.Select(t => t.Slug).Take(20)));
        }
        return tenant;
    }

    // ---------- Staff ----------

    private static List<StaffMember> SeedStaff(CafePosDbContext db, int tenantId)
    {
        var existing = db.Staff.IgnoreQueryFilters().Where(s => s.TenantId == tenantId && s.Email!.EndsWith(DemoEmailDomain)).ToList();
        if (existing.Count > 0) return existing;

        var joined = DateTime.UtcNow.AddMonths(-14);
        var staff = Roster.Select((r, i) => new StaffMember
        {
            TenantId = tenantId,
            Name = r.Name,
            Role = r.Role,
            Email = $"{r.Name.Split(' ')[0].ToLowerInvariant()}.{r.Name.Split(' ')[1].ToLowerInvariant()}{DemoEmailDomain}",
            Phone = r.Phone,
            Status = StaffStatus.Active,
            JoinedAt = joined.AddDays(i * 23),
            Department = r.Department,
            Designation = r.Designation,
            SalaryType = SalaryType.Monthly,
            BasicSalary = r.BasicSalary,
            HourlyRate = Math.Round(r.BasicSalary / 30m / 8m, 2),
            BankAccountNumber = r.Account,
            BankIfsc = r.Ifsc,
            BankName = r.Ifsc.StartsWith("HDFC") ? "HDFC Bank" : r.Ifsc.StartsWith("ICIC") ? "ICICI Bank" : "State Bank of India",
            Pan = $"ABCDE{1000 + i}F",
        }).ToList();

        db.Staff.AddRange(staff);
        db.SaveChanges(); // ids are needed by everything below
        return staff;
    }

    /// <summary>
    /// My Attendance and My Payslips resolve their data through StaffMember.UserId ==
    /// the caller's user id, and hard-fail with "This login has no linked staff roster
    /// entry" when there isn't one — an owner who registered a cafe has no roster row by
    /// default. So the first demo roster entry is adopted by the tenant's owner login and
    /// renamed to them; without this the two self-service screens stay unreachable no
    /// matter how much attendance data exists.
    /// </summary>
    private static void LinkSignedInOwnerToRoster(CafePosDbContext db, ILogger logger, int tenantId, string? ownerEmail, List<StaffMember> staff)
    {
        if (staff.Count == 0) return;

        // Prefer the exact login the seed was aimed at; otherwise the cafe's owner.
        var owner = (string.IsNullOrWhiteSpace(ownerEmail) ? null : db.Users.FirstOrDefault(u => u.Email == ownerEmail))
            ?? db.Users.Where(u => u.TenantId == tenantId && !u.IsPlatformAdmin)
                .OrderBy(u => u.Role == AppRole.Owner ? 0 : 1).ThenBy(u => u.Id)
                .FirstOrDefault();
        if (owner is null)
        {
            logger.LogWarning("DemoData: tenant has no login to attach the roster to — My Attendance / My Payslips will stay empty.");
            return;
        }

        // Their own roster entry already exists (real or from an earlier run) — leave it alone.
        if (db.Staff.IgnoreQueryFilters().Any(s => s.UserId == owner.Id)) return;

        var mine = staff[0];
        mine.UserId = owner.Id;
        mine.Name = owner.Name;
        mine.Phone = owner.Phone ?? mine.Phone;
        db.SaveChanges();
        logger.LogInformation("DemoData: linked roster entry '{Name}' to login {Email} for the self-service screens.", mine.Name, owner.Email);
    }

