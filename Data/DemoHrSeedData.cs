    // ---------- Shifts + attendance ----------

    /// <summary>
    /// Sundays are the weekly off (no shift, no record). Absent days are represented the
    /// way the app itself defines them — a scheduled Shift with no AttendanceRecord against
    /// it — because AttendanceRecord.Status never stores Absent (see its doc comment).
    /// </summary>
    private static void SeedShiftsAndAttendance(CafePosDbContext db, int tenantId, List<StaffMember> staff, DateOnly from, DateOnly to)
    {
        for (var s = 0; s < staff.Count; s++)
        {
            var member = staff[s];
            var dayIndex = 0;
            for (var date = from; date <= to; date = date.AddDays(1))
            {
                if (date.DayOfWeek == DayOfWeek.Sunday) continue;
                dayIndex++;

                var shiftStart = date.ToDateTime(new TimeOnly(9, 0));
                db.Shifts.Add(new Shift { TenantId = tenantId, StaffId = member.Id, StartsAt = shiftStart, EndsAt = shiftStart.AddHours(8) });

                // Staggered per staff member so the roster doesn't march in lockstep.
                var slot = (dayIndex + s * 3) % 12;
                if (slot == 4) continue; // absent: shift scheduled, nobody punched in

                var isLate = slot == 1;
                var isHalfDay = slot == 7;
                var hasOvertime = slot == 9;

                var punchIn = shiftStart.AddMinutes(isLate ? 25 : -4);
                var punchOut = isHalfDay ? shiftStart.AddHours(4) : shiftStart.AddHours(hasOvertime ? 9.5 : 8).AddMinutes(6);
                var breakMinutes = isHalfDay ? 0 : 30;
                var worked = (int)(punchOut - punchIn).TotalMinutes - breakMinutes;
                var overtime = Math.Max(0, worked - 8 * 60);

                db.AttendanceRecords.Add(new AttendanceRecord
                {
                    TenantId = tenantId,
                    StaffId = member.Id,
                    Date = date,
                    PunchInAt = punchIn,
                    PunchOutAt = punchOut,
                    BreakMinutes = breakMinutes,
                    WorkedMinutes = worked,
                    Status = isHalfDay ? AttendanceStatus.HalfDay : isLate ? AttendanceStatus.Late : AttendanceStatus.Present,
                    LateMinutes = isLate ? 15 : 0,
                    OvertimeMinutes = overtime,
                });
            }
        }
    }

    // ---------- Payroll ----------

    /// <summary>
    /// A finalized (Paid) run for last month, so My Payslips and the payslip PDF have
    /// something to show without anyone having to run the real generator first.
    ///
    /// The arithmetic below mirrors PayrollController's Monthly branch (every demo staff
    /// member is SalaryType.Monthly) and reuses the real StatutoryDeductionCalculator, but
    /// it is a copy, not the same code — the generator's version lives on private methods
    /// of the controller. Treat the real thing as the source of truth: generating a fresh
    /// run from the Payroll Runs screen is what exercises it.
    /// </summary>
    private static void SeedPaidPayrollRun(
        CafePosDbContext db,
        int tenantId,
        List<StaffMember> staff,
        List<StaffLoan> loans,
        List<LeaveRequest> leaves,
        CafeSettings settings,
        DateOnly periodStart,
        DateOnly periodEnd)
    {
        var attendance = db.AttendanceRecords.IgnoreQueryFilters()
            .Where(a => a.TenantId == tenantId && a.Date >= periodStart && a.Date <= periodEnd)
            .ToList();
        var shiftDates = db.Shifts.IgnoreQueryFilters()
            .Where(s => s.TenantId == tenantId)
            .Select(s => new { s.StaffId, s.StartsAt })
            .ToList();

        var periodDays = periodEnd.DayNumber - periodStart.DayNumber + 1;
        var monthRatio = periodDays / 30m;
        var run = new PayrollRun
        {
            TenantId = tenantId,
            PeriodStart = periodStart,
            PeriodEnd = periodEnd,
            Status = PayrollRunStatus.Paid,
            GeneratedAt = periodEnd.ToDateTime(new TimeOnly(18, 0)),
            GeneratedByName = "Owner",
            LockedAt = periodEnd.ToDateTime(new TimeOnly(18, 30)),
            PaidAt = periodEnd.ToDateTime(new TimeOnly(19, 0)),
            Notes = DemoRunNote,
        };

        foreach (var member in staff)
        {
            var mine = attendance.Where(a => a.StaffId == member.Id).ToList();
            var attended = mine.Where(a => a.WorkedMinutes.HasValue).Select(a => a.Date).ToHashSet();
            var presentDays = attended.Count;
            var lateDays = mine.Count(a => a.Status == AttendanceStatus.Late);
            var halfDays = mine.Count(a => a.Status == AttendanceStatus.HalfDay);
            var overtimeHours = mine.Sum(a => a.OvertimeMinutes) / 60.0;

            var myLeave = leaves.Where(l => l.StaffId == member.Id && l.Status == LeaveRequestStatus.Approved
                && l.StartDate <= periodEnd && l.EndDate >= periodStart).ToList();
            var leaveDates = new HashSet<DateOnly>();
            int paidLeaveDays = 0, unpaidLeaveDays = 0;
            foreach (var leave in myLeave)
            {
                var start = leave.StartDate > periodStart ? leave.StartDate : periodStart;
                var end = leave.EndDate < periodEnd ? leave.EndDate : periodEnd;
                var days = end.DayNumber - start.DayNumber + 1;
                if (leave.Type == LeaveType.Unpaid) unpaidLeaveDays += days; else paidLeaveDays += days;
                for (var d = start; d <= end; d = d.AddDays(1)) leaveDates.Add(d);
            }

            var scheduled = shiftDates.Where(s => s.StaffId == member.Id)
                .Select(s => DateOnly.FromDateTime(s.StartsAt))
                .Where(d => d >= periodStart && d <= periodEnd)
                .Distinct().ToList();
            var absentDays = scheduled.Count(d => !attended.Contains(d) && !leaveDates.Contains(d));

            var monthlyBasic = member.BasicSalary ?? 0;
            var perDayRate = monthlyBasic / 30m;
            var basePay = Math.Round(monthlyBasic * monthRatio, 2);
            var hourlyEquivalent = settings.StandardShiftHours > 0 ? perDayRate / settings.StandardShiftHours : 0;
            var overtimePay = Math.Round((decimal)overtimeHours * hourlyEquivalent * 1.5m, 2);
            var grossBeforeAllowances = basePay + overtimePay;

            var line = new PayrollLine
            {
                TenantId = tenantId,
                StaffId = member.Id,
                StaffName = member.Name,
                SalaryType = member.SalaryType,
                BasicSalary = basePay,
                HourlyRate = member.HourlyRate,
                PresentDays = presentDays,
                LateDays = lateDays,
                HalfDays = halfDays,
                AbsentDays = absentDays,
                PaidLeaveDays = paidLeaveDays,
                UnpaidLeaveDays = unpaidLeaveDays,
                OvertimeHours = overtimeHours,
                OvertimePay = overtimePay,
                Allowances = [],
                LeaveDeduction = Math.Round(unpaidLeaveDays * perDayRate, 2),
                LateDeduction = Math.Round(lateDays * perDayRate * 0.1m, 2),
                LoanDeduction = loans.Where(l => l.StaffId == member.Id).Sum(l => Math.Min(l.MonthlyDeduction, l.OutstandingBalance)),
                PfDeduction = StatutoryDeductionCalculator.Pf(basePay, StatutoryDeductionCalculator.MonthlyPfWageCeiling * monthRatio),
                EsicDeduction = StatutoryDeductionCalculator.Esic(grossBeforeAllowances, StatutoryDeductionCalculator.MonthlyEsicGrossCeiling * monthRatio),
                ProfessionalTaxDeduction = StatutoryDeductionCalculator.ProfessionalTax(
                    grossBeforeAllowances,
                    StatutoryDeductionCalculator.MonthlyProfessionalTaxThreshold * monthRatio,
                    StatutoryDeductionCalculator.MonthlyProfessionalTaxFlat * monthRatio),
                BankAccountNumberSnapshot = member.BankAccountNumber,
                BankIfscSnapshot = member.BankIfsc,
            };
            Finalize(line);
            run.Lines.Add(line);

            // The run is seeded as already Paid, and MarkPaid is what draws down a loan —
            // so the balances have to reflect this run's deduction or they'd read as unpaid.
            var remaining = line.LoanDeduction;
            foreach (var loan in loans.Where(l => l.StaffId == member.Id))
            {
                if (remaining <= 0) break;
                var take = Math.Min(remaining, loan.OutstandingBalance);
                loan.OutstandingBalance -= take;
                remaining -= take;
                if (loan.OutstandingBalance > 0) continue;
                loan.Status = LoanStatus.Closed;
                loan.ClosedAt = DateTime.UtcNow;
            }
        }

        db.PayrollRuns.Add(run);
    }

    /// <summary>Mirror of PayrollController.FinalizeLine — see SeedPaidPayrollRun's note.</summary>
    private static void Finalize(PayrollLine line)
    {
        line.AllowancesTotal = line.Allowances.Sum(a => a.Amount);
        line.GrossEarnings = line.BasicSalary + line.OvertimePay + line.AllowancesTotal;
        var nonLoan = line.LeaveDeduction + line.LateDeduction + line.PfDeduction + line.EsicDeduction + line.ProfessionalTaxDeduction;
        line.LoanDeduction = Math.Min(line.LoanDeduction, Math.Max(0, line.GrossEarnings - nonLoan));
        line.TotalDeductions = nonLoan + line.LoanDeduction;
        line.NetSalary = Math.Max(0, line.GrossEarnings - line.TotalDeductions);
    }

    // ---------- Purge ----------

    private static void Purge(CafePosDbContext db, ILogger logger, int tenantId)
    {
        var staffIds = db.Staff.IgnoreQueryFilters()
            .Where(s => s.TenantId == tenantId && s.Email!.EndsWith(DemoEmailDomain))
            .Select(s => s.Id).ToList();
        if (staffIds.Count == 0)
        {
            logger.LogInformation("DemoData: nothing to purge for tenant {TenantId}.", tenantId);
            return;
        }

        db.PayrollLines.RemoveRange(db.PayrollLines.IgnoreQueryFilters().Where(l => l.TenantId == tenantId && staffIds.Contains(l.StaffId)));
        db.PayrollRuns.RemoveRange(db.PayrollRuns.IgnoreQueryFilters().Where(r => r.TenantId == tenantId && r.Notes == DemoRunNote));
        db.StaffLoans.RemoveRange(db.StaffLoans.IgnoreQueryFilters().Where(l => l.TenantId == tenantId && staffIds.Contains(l.StaffId)));
        db.LeaveRequests.RemoveRange(db.LeaveRequests.IgnoreQueryFilters().Where(l => l.TenantId == tenantId && staffIds.Contains(l.StaffId)));
        db.AttendanceRecords.RemoveRange(db.AttendanceRecords.IgnoreQueryFilters().Where(a => a.TenantId == tenantId && staffIds.Contains(a.StaffId)));
        db.AttendanceLogs.RemoveRange(db.AttendanceLogs.IgnoreQueryFilters().Where(a => a.TenantId == tenantId && staffIds.Contains(a.StaffId)));
        db.Shifts.RemoveRange(db.Shifts.IgnoreQueryFilters().Where(s => s.TenantId == tenantId && staffIds.Contains(s.StaffId)));
        db.Staff.RemoveRange(db.Staff.IgnoreQueryFilters().Where(s => staffIds.Contains(s.Id)));
        db.SaveChanges();

        logger.LogWarning("DemoData: purged demo HR data ({Count} staff and everything hanging off them) from tenant {TenantId}.", staffIds.Count, tenantId);
    }
